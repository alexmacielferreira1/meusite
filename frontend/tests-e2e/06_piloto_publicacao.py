import os
from uuid import uuid4
from playwright.sync_api import sync_playwright, expect

base = os.getenv("FOLIOCOM_TEST_URL", "http://localhost:8000")
suffix = uuid4().hex[:8]
browser_binary = os.getenv("CHROMIUM_EXECUTABLE")
errors = []
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=browser_binary, args=["--no-sandbox", "--disable-gpu"])
    owner = browser.new_context(viewport={"width": 1440, "height": 950})
    visitor = browser.new_context(viewport={"width": 390, "height": 844})
    page = owner.new_page()
    view = visitor.new_page()
    for tab in (page, view):
        tab.on("pageerror", lambda err: errors.append(str(err)))
    view.goto(base + "/app")
    expect(view.get_by_role("heading", name="Entrar")).to_be_visible()
    page.goto(base + "/cadastro")
    page.get_by_role("textbox").nth(0).fill("Alex QA " + suffix)
    page.locator("input[type=email]").fill(f"alex-{suffix}@example.test")
    page.locator("input[type=password]").fill("senha-desenvolvimento-123")
    page.get_by_role("button", name="Criar conta").click()
    page.wait_for_url("**/app/comecar")
    page.get_by_role("button", name="Continuar").click()
    page.get_by_role("button", name="Continuar").click()
    page.get_by_role("button", name="Gerar meu portfólio").click()
    expect(page.get_by_text("Seu rascunho está pronto!")).to_be_visible()
    page.get_by_role("button", name="Subir meus trabalhos primeiro").click()
    page.get_by_role("link", name="Trabalhos", exact=True).click()
    page.get_by_role("button", name="Novo trabalho").click()
    page.get_by_placeholder("https://www.youtube.com/watch?v=…").fill("https://www.youtube.com/watch?v=dQw4w9WgXcQ")
    page.get_by_placeholder("Ex.: Rios do Brasil").fill("Documentário sobre a Orla")
    page.get_by_placeholder("Direção, roteiro e edição").fill("Montagem documental")
    page.get_by_placeholder("Quais decisões e etapas ficaram sob sua responsabilidade?").fill("Editei entrevistas no DaVinci Resolve.")
    page.get_by_role("textbox", name="Timecode").fill("02:15")
    page.get_by_role("textbox", name="Descrição do momento").fill("Montagem das entrevistas")
    page.get_by_role("button", name="Adicionar", exact=True).click()
    with page.expect_response(lambda r: r.url.endswith("/api/v1/sites/me") and r.request.method == "PUT" and r.ok):
        page.get_by_role("button", name="Salvar trabalho").click()
    page.get_by_role("link", name="Publicação", exact=True).click()
    page.get_by_role("button", name="Publicar site", exact=True).click()
    expect(page.get_by_text("Versão publicada.")).to_be_visible()
    href = page.get_by_role("link", name="Abrir", exact=True).get_attribute("href")
    view.goto(base + href)
    expect(view.get_by_text("Documentário sobre a Orla").first).to_be_visible()
    assert view.evaluate("document.documentElement.scrollWidth <= innerWidth")
    page.get_by_role("link", name="Oportunidades", exact=True).click()
    page.get_by_placeholder("Ex. · Edição de documentário para produtora").fill("Vaga de montagem")
    page.get_by_placeholder("Ex. · Montagem documental, entrevistas e DaVinci Resolve.").fill("Montagem documental e DaVinci Resolve")
    page.get_by_role("button", name="Selecionar sugestões").click()
    page.get_by_role("button", name="Publicar link").click()
    expect(page.get_by_text("Link publicado. Copie o endereço na lista abaixo.")).to_be_visible()
    opportunity = page.get_by_role("link", name="Abrir", exact=True).get_attribute("href")
    view.goto(base + opportunity)
    expect(view.get_by_text("Seleção para Vaga de montagem")).to_be_visible()
    expect(view.get_by_text("Documentário sobre a Orla").first).to_be_visible()
    view.get_by_role("button", name="Documentário sobre a Orla", exact=False).first.click()
    expect(view.get_by_text("Editei entrevistas no DaVinci Resolve.")).to_be_visible()
    expect(view.get_by_role("button", name="02:15 · Montagem das entrevistas")).to_be_visible()
    page.get_by_role("button", name="Desativar", exact=True).click()
    expect(page.get_by_text("Desativado ·", exact=False)).to_be_visible()
    view.reload()
    expect(view.get_by_text("Este link expirou, foi desativado ou não existe.")).to_be_visible()
    page.reload()
    expect(page.get_by_text("Vaga de montagem")).to_be_visible()
    assert not errors, errors
    browser.close()
print("Smoke Chromium: cadastro, onboarding, trabalho, publicação, vitrine, timecode, revogação e recarga passaram.")
